/** 1 → "1st", 2 → "2nd", 3 → "3rd", 11 → "11th". */
function ordinal(position: number): string {
  const teen = position % 100 >= 11 && position % 100 <= 13;
  const suffix = teen ? "th" : (["th", "st", "nd", "rd"][position % 10] ?? "th");
  return `${position}${suffix}`;
}
